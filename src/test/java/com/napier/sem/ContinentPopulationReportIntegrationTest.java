
package com.napier.sem;

import org.junit.jupiter.api.Test;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Integration tests for ContinentPopulationReport.
 *
 * These tests verify that continent population reports retrieve and display
 * accurate population information from the World database. They check
 * individual continent population lookups, handling of unknown continent
 * names, total/urban/non-urban population breakdowns, percentage calculations
 * and alphabetical ordering of continents.
 *
 * The expected results are retrieved independently using SQL queries and
 * compared with the output generated by the report methods.
 */
class ContinentPopulationReportIntegrationTest {

    /**
     * Verifies that the population lookup for Asia displays the correct
     * continent name and total population retrieved from the database.
     */
    @Test
    void shouldDisplayCorrectAsianPopulation() throws Exception {

        long expectedPopulation;

        // Retrieve the expected Asian population directly from the database.
        try (Connection connection = DatabaseConnection.getConnection();
             Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(
                     "SELECT SUM(Population) AS TotalPopulation " +
                             "FROM country WHERE Continent = 'Asia'")) {

            assertTrue(resultSet.next());
            expectedPopulation = resultSet.getLong("TotalPopulation");
            assertFalse(resultSet.wasNull());
        }

        // Capture the console output generated by the report method.
        String reportOutput = captureOutput(
                () -> ContinentPopulationReport.showPopulation("Asia")
        );

        // Verify the report title, continent name and expected population.
        assertTrue(reportOutput.contains(
                "--- Continent Population Report ---"
        ));
        assertTrue(reportOutput.contains("Continent: Asia"));
        assertTrue(reportOutput.contains(
                String.format("%,d", expectedPopulation)
        ));
    }

    /**
     * Verifies that an appropriate error message is displayed when the
     * requested continent does not exist in the database.
     */
    @Test
    void shouldDisplayMessageWhenContinentIsNotFound() {

        // Request a continent name that should not exist in the database.
        String reportOutput = captureOutput(
                () -> ContinentPopulationReport.showPopulation(
                        "NotARealContinent"
                )
        );

        // Verify that both not-found and guidance messages are displayed.
        assertTrue(reportOutput.contains(
                "Continent not found: NotARealContinent"
        ));
        assertTrue(reportOutput.contains(
                "Please check the name and try again."
        ));
    }

    /**
     * Verifies that the population breakdown report displays the correct
     * total, urban and non-urban population figures and percentages for
     * every continent in the World database.
     */
    @Test
    void shouldDisplayCorrectPopulationBreakdownForEveryContinent()
            throws Exception {

        // Retrieve independent population totals for each continent.
        String sql = """
                SELECT
                    co.Continent,
                    SUM(co.Population) AS TotalPopulation,
                    SUM(COALESCE(ct.UrbanPopulation, 0)) AS UrbanPopulation
                FROM country co
                LEFT JOIN (
                    SELECT CountryCode,
                           SUM(Population) AS UrbanPopulation
                    FROM city
                    GROUP BY CountryCode
                ) ct ON co.Code = ct.CountryCode
                GROUP BY co.Continent
                ORDER BY co.Continent
                """;

        List<String> expectedRows = new ArrayList<>();

        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {

            // Calculate the expected population breakdown for each continent.
            while (resultSet.next()) {

                String continent = resultSet.getString("Continent");
                long totalPopulation =
                        resultSet.getLong("TotalPopulation");
                long urbanPopulation =
                        resultSet.getLong("UrbanPopulation");

                PopulationCalculator.Breakdown breakdown =
                        PopulationCalculator.calculate(
                                totalPopulation,
                                urbanPopulation
                        );

                // Format expected values using the report's output format.
                expectedRows.add(String.format(
                        "%-25s %,15d %,15d %,15d %11.2f%% %14.2f%%",
                        continent,
                        breakdown.totalPopulation(),
                        breakdown.urbanPopulation(),
                        breakdown.nonUrbanPopulation(),
                        breakdown.urbanPercentage(),
                        breakdown.nonUrbanPercentage()
                ));
            }
        }

        // Ensure the database contains continent records to test.
        assertFalse(
                expectedRows.isEmpty(),
                "The database should contain continent records."
        );

        // Capture the output from the population breakdown report.
        String reportOutput = captureOutput(
                ContinentPopulationReport::populationByContinent
        );

        // Verify that the report title and percentage heading are displayed.
        assertTrue(reportOutput.contains(
                "--- Population Breakdown by Continent ---"
        ));
        assertTrue(reportOutput.contains("Continent"));
        assertTrue(reportOutput.contains("Non-urban %"));

        // Verify that every expected population row appears in the correct
        // alphabetical order.
        int previousPosition = -1;

        for (String expectedRow : expectedRows) {

            int currentPosition = reportOutput.indexOf(expectedRow);

            assertTrue(
                    currentPosition >= 0,
                    "Expected population row was not displayed: "
                            + expectedRow
            );

            assertTrue(
                    currentPosition > previousPosition,
                    "Continents should appear in alphabetical order."
            );

            previousPosition = currentPosition;
        }
    }

    /**
     * Verifies that the population breakdown report displays all continents
     * in alphabetical order, matching the ordering used by the database.
     */
    @Test
    void shouldDisplayContinentsInAlphabeticalOrder() throws Exception {

        List<String> expectedContinents = new ArrayList<>();

        // Retrieve the expected continent order using the database collation.
        try (Connection connection = DatabaseConnection.getConnection();
             Statement statement = connection.createStatement();
             ResultSet resultSet = statement.executeQuery(
                     "SELECT DISTINCT Continent FROM country " +
                             "ORDER BY Continent")) {

            while (resultSet.next()) {
                expectedContinents.add(
                        resultSet.getString("Continent")
                );
            }
        }

        assertFalse(
                expectedContinents.isEmpty(),
                "The database should contain continent records."
        );

        // Capture the actual continent population report.
        String reportOutput = captureOutput(
                ContinentPopulationReport::populationByContinent
        );

        // Check that every continent appears in the expected order.
        int previousPosition = -1;

        for (String continent : expectedContinents) {

            int currentPosition = reportOutput.indexOf(continent);

            assertTrue(
                    currentPosition >= 0,
                    "Continent should appear in the report: " + continent
            );

            assertTrue(
                    currentPosition > previousPosition,
                    "Continents should be displayed alphabetically."
            );

            previousPosition = currentPosition;
        }
    }

    /**
     * Captures System.out while a report method executes, allowing tests
     * to verify the text displayed by console-based reports.
     *
     * @param report report method to execute
     * @return captured console output as a string
     */
    private String captureOutput(Runnable report) {

        PrintStream originalOut = System.out;
        ByteArrayOutputStream output = new ByteArrayOutputStream();

        try (PrintStream capturedOut =
                     new PrintStream(output, true, StandardCharsets.UTF_8)) {

            System.setOut(capturedOut);
            report.run();

        } finally {
            // Restore the original console output even if the report fails.
            System.setOut(originalOut);
        }

        return output.toString(StandardCharsets.UTF_8);
    }
}